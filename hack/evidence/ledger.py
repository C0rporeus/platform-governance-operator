import sys, json, csv
# usage: python3 -I ledger.py SOURCES_DIR REVIEW_STATUS_TSV MANIFEST_TSV > source-ledger.md
src, status, man = sys.argv[1:4]
log={}
for l in open(f"{src}/_fetch.log"):
    p=l.rstrip("\n").split("\t"); 
    if len(p)==5: log[p[0]]=p
st={r[0]:r for r in csv.reader(open(status),delimiter="\t")}
print("# Source Ledger\n")
print("Generated by `hack/evidence/ledger.py` from `hack/evidence/` inputs. Each source was downloaded whole, hashed (SHA-256 of the raw bytes), converted to text and sectioned. Copies are **not** stored in the repository (licences differ); the hash identifies exactly what was read.\n")
print("| ID | URL | Retrieved (UTC) | HTTP | SHA-256 (first 16) | Text chars | Headings | Review status | Date | Note |")
print("| :--- | :--- | :--- | :---: | :--- | ---: | ---: | :--- | :--- | :--- |")
for r in csv.reader(open(man),delimiter="\t"):
    sid,url=r[0],r[1]
    try: meta=json.load(open(f"{src}/{sid}/meta.json"))
    except Exception: meta={"chars":"-","headings":"-"}
    l=log.get(sid,[sid,"|".join(["-","-","-"]),"-","-",url]); code=l[1].split("|")[0]
    s=st.get(sid,[sid,"Not reviewed","-","-"])
    print(f"| {sid} | {url} | {l[3]} | {code} | `{l[2][:16]}` | {meta['chars']} | {meta['headings']} | {s[1]} | {s[2]} | {s[3]} |")
print("\n**Blocked:** S-22 (ISO/IEC 27001:2022). `iso.org` answers HTTP 403 to automated clients and no browser session was available; see `ENAB-05.6`.")
